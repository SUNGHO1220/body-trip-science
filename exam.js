const XT = (head, rows, note) => `<div class="tbw"><table class="tb"><thead><tr>${head.map(h => `<th>${h}</th>`).join('')}</tr></thead><tbody>${rows.map(r => `<tr><th>${r[0]}</th>${r.slice(1).map(c => `<td>${c}</td>`).join('')}</tr>`).join('')}</tbody></table></div>${note ? `<p class="exnote">${note}</p>` : ''}`;
const XD = s => `<div class="exd">${s}</div>`;
const XG = {
  wrap: (w, h, s) => `<figure class="figw"><svg class="fig" viewBox="0 0 ${w} ${h}" role="img">${s}</svg></figure>`,
  axis: (L, T, W, R, H, B, yl) => `<path d="M${L} ${T - 8}V${H - B}H${W - R}" fill="none" stroke="#333" stroke-width="1.5"/><text class="s" x="4" y="13">${yl}</text>`,
  // 꺾은선 그래프. ser: [{ n: 이름, v: 값, c: 색, d: 점선, o: 겹침 방지용 세로 이동(px) }]
  line({ xs, ser, ymin = 0, ymax = 100, yt = [ymin, ymax], yl = '', xl = '', bands = [], ref }) {
    const W = 360, H = 236, L = 40, R = 14, T = 42, B = 40;
    const px = i => L + (W - L - R) * i / (xs.length - 1);
    const py = v => T + (H - T - B) * (ymax - v) / (ymax - ymin);
    const dash = r => r.d ? ' stroke-dasharray="6 4"' : '';
    let s = bands.map(([a, b, t], k) => `<rect x="${px(a)}" y="${T}" width="${px(b) - px(a)}" height="${H - T - B}" fill="${k % 2 ? '#fbf8ef' : '#f1ecdc'}"/><text class="s" x="${(px(a) + px(b)) / 2}" y="${T + 14}" text-anchor="middle">${t}</text>`).join('');
    if (ref) s += `<line x1="${L}" x2="${W - R}" y1="${py(ref[0])}" y2="${py(ref[0])}" stroke="#999" stroke-dasharray="4 3"/><text class="s" x="${L + 4}" y="${py(ref[0]) - 5}">${ref[1]}</text>`;
    s += XG.axis(L, T, W, R, H, B, yl);
    s += yt.map(v => `<text class="s" x="${L - 6}" y="${py(v) + 4}" text-anchor="end">${v}</text>`).join('');
    s += xs.map((x, i) => `<text class="s" text-anchor="middle" y="${H - B + 15}">${x.split('\n').map((t, j) => `<tspan x="${px(i)}" dy="${j ? 13 : 0}">${t}</tspan>`).join('')}</text>`).join('');
    if (xl) s += `<text class="s" x="${W - R}" y="${H - 4}" text-anchor="end">${xl}</text>`;
    s += ser.map((r, k) => {
      const lx = W - R - 66 * (ser.length - k);
      return `<polyline points="${r.v.map((v, i) => `${px(i)},${py(v) + (r.o || 0)}`).join(' ')}" fill="none" stroke="${r.c}" stroke-width="2.5"${dash(r)}/>` +
        (r.n ? `<line x1="${lx}" x2="${lx + 18}" y1="27" y2="27" stroke="${r.c}" stroke-width="2.5"${dash(r)}/><text class="s" x="${lx + 22}" y="31">${r.n}</text>` : '');
    }).join('');
    return XG.wrap(W, H, s);
  },
  // 막대그래프
  bar({ xs, v, ymax = 100, yt = [0, ymax], yl = '' }) {
    const W = 360, H = 200, L = 40, R = 14, T = 28, B = 26, sw = (W - L - R) / xs.length;
    const py = y => T + (H - T - B) * (ymax - y) / ymax;
    let s = XG.axis(L, T, W, R, H, B, yl);
    s += yt.map(y => `<text class="s" x="${L - 6}" y="${py(y) + 4}" text-anchor="end">${y}</text>`).join('');
    s += xs.map((x, i) => {
      const cx = L + sw * (i + .5);
      return `<rect x="${cx - sw * .22}" y="${py(v[i])}" width="${sw * .44}" height="${H - B - py(v[i])}" style="fill:var(--c)"/><text class="s" x="${cx}" y="${py(v[i]) - 5}" text-anchor="middle">${v[i]}</text><text class="s" x="${cx}" y="${H - B + 16}" text-anchor="middle">${x}</text>`;
    }).join('');
    return XG.wrap(W, H, s);
  },
};
